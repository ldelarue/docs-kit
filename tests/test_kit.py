def test_glue_block_canonical_idempotent_and_drift_gated(tmp_path, capsys):
    repo = make_cli_repo(tmp_path, "toolrepo")
    assert cli.cmd_init(repo, SPEC, False, use_mise=True, committed_mise=True) == 0
    text = (repo / "mise.toml").read_text()
    assert text == glue.glue_block(True, False) + "\n"
    cfg = tomllib.loads(text)
    assert cfg["tools"]["usage"] == "latest"
    assert cfg["tasks"]["cli:spec"]["run"] == "uv run docs-kit spec"
    assert "docs-kit check && git diff" in cfg["tasks"]["docs:check"]["run"]
    ign = (repo / ".gitignore").read_text().split()
    assert "mise.local.toml" in ign and ".docs-kit/" not in ign
    assert not (repo / ".docs-kit").exists()
    assert not (repo / "mise.local.toml").exists()
    before = (repo / "mise.toml").read_bytes()
    assert cli.cmd_init(repo, SPEC, False, use_mise=True, committed_mise=True) == 0
    assert (repo / "mise.toml").read_bytes() == before  # idempotent
    assert cli.cmd_check(repo, SPEC) == 0
    # hand-tweak inside the block = drift, remediation names the command
    (repo / "mise.toml").write_text(
        text.replace('run = "uv run docs-kit spec"', 'run = "echo nope"')
    )
    assert cli.cmd_check(repo, SPEC) == 1
    err = capsys.readouterr().err
    assert "docs-kit task block" in err and "--committed" in err
    assert cli.cmd_init(repo, SPEC, False, use_mise=True, committed_mise=True) == 0
    assert (repo / "mise.toml").read_text() == text  # repaired


