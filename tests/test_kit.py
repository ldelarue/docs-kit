def make_cli_repo(
    base: Path, name: str, *, typer: bool = True, kdl: tuple = ()
) -> Path:
    repo = base / name
    repo.mkdir(parents=True)
    if typer:
        (repo / "pyproject.toml").write_text(TYPER_PYPROJECT)
    for bin_name in kdl:
        d = repo / "cli"
        d.mkdir(exist_ok=True)
