def _fake_server(monkeypatch):
    calls = []

    class _Done:
        returncode = 0

    monkeypatch.setattr(
        serve.subprocess, "run", lambda cmd, **kw: calls.append(cmd) or _Done()
    )
    return calls


def _served(addr):
    return [[sys.executable, "-m", "zensical", "serve", "--dev-addr", addr]]


